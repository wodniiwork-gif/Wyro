import Foundation

/// What Claude is helping with. Each mode has its own instructions.
enum AssistantMode: String, CaseIterable, Identifiable {
  case general
  case barber
  case artist
  case stylist

  var id: String { rawValue }

  var title: String {
    switch self {
    case .general: return "Обычный"
    case .barber: return "Барбер"
    case .artist: return "Артист"
    case .stylist: return "Стилист"
    }
  }

  /// Spoken in the glasses after switching.
  var announcement: String {
    switch self {
    case .general: return "Обычный режим."
    case .barber: return "Режим барбера. Спрашивай, я смотрю."
    case .artist: return "Режим артиста. Давай строчки."
    case .stylist: return "Режим стилиста. Показывай, что примеряем."
    }
  }

  /// Tip shown under the mode picker.
  var hint: String {
    switch self {
    case .general:
      return "«Клод, что это и сколько стоит?», «Клод, что тут написано?», «Клод, какой лучше?»"
    case .barber:
      return "Смотри на зону 1–2 сек: «Клод, где линия?», «Клод, как убрать вот это?». Переводчик: «Клод, слушай клиента», «Клод, скажи клиенту …»"
    case .artist:
      return "«Клод, рифма к …», «Клод, почему строчка сырая: …», «Клод, запомни строчку …», «Клод, прочитай строчки», «Клод, хэштеги»"
    case .stylist:
      return "Смотри на вещь или в зеркало: «Клод, как эта вещь?», «Клод, сочетается образ?», «Клод, с чем это носить?», «Клод, какую из двух брать?»"
    }
  }

  var systemPrompt: String {
    switch self {
    case .general: return Self.generalPrompt
    case .barber: return Self.barberPrompt
    case .artist: return Self.artistPrompt
    case .stylist: return Self.stylistPrompt
    }
  }

  /// Image helps in general and barber mode; in artist mode only when asked
  /// about something visible (screen with a mixer, a place for a video).
  var picturesByDefault: Bool { self != .artist }

  private static let common = """
    Ты — WYRO, голосовой ИИ-помощник в умных очках Ray-Ban Meta (работаешь на модели Claude от Anthropic; приложение создал Art Anzhelii). Пользователь говорит по-русски, \
    живёт в Ирландии. К вопросу может быть приложен кадр с камеры очков — это то, что он видит прямо сейчас. \
    Слова «это», «вот это», «здесь», «тут» означают то, что в центре кадра.
    Ответ зачитывается вслух в очках, поэтому: говори по-русски, без списков, markdown, эмодзи и ссылок, \
    только обычная живая речь. Не определяй личности людей по лицу.
